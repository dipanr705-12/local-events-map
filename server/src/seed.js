function seedDatabase() {
  console.log('Clearing existing events...');
  db.exec('DELETE FROM events;');

  const insertStmt = db.prepare(`
    INSERT INTO events (
      title, description, category, date, time, endDate, endTime,
      venue, address, latitude, longitude, price, organizer, imageUrl, website
    ) VALUES (
      ?, ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?, ?, ?, ?
    )
  `);

  let count = 0;
  for (const ev of sampleEvents) {
    const computedDate = getOffsetDate(ev.daysOffset);
    insertStmt.run(
      ev.title,
      ev.description,
      ev.category,
      computedDate,
      ev.time,
      computedDate,
      ev.endTime || null,
      ev.venue,
      ev.address,
      ev.latitude,
      ev.longitude,
      ev.price,
      ev.organizer,
      ev.imageUrl,
      ev.website
    );
    count++;
  }

  console.log(`Successfully seeded ${count} events (including ${durgaPujaPandals.length} Durga Puja Pandals in West Bengal) into database!`);
  return count;
}

if (require.main === module) {
  seedDatabase();
}

